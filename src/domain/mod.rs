//! # 领域术语
//!
//! | 术语 | 含义 | 权威范围 |
//! |---|---|---|
//! | 全局身份 `Identity` | 与平台用户唯一绑定的 LR 账号 | 全项目 |
//! | 界 `World` | 一个启用 LR 的群对应的独立世界 | 单群 |
//! | 本地化身 `Avatar` | 某身份在某一界内成长的角色 | 单界 |
//! | 跨界投影 `Projection` | 化身在目标界的受限表现 | 来源界与目标界之间 |
//!
//! 当前数据库仍以 `players.player_id` 为中心，且该列的值恰为平台 QQ 号的
//! `i64` 表示；P1 迁移会把它拆分为 `IdentityId` 加 `AvatarId`。在迁移完成
//! 前，新代码不得把 [`PlayerId`](shared::PlayerId) 与
//! [`PlatformUserId`](shared::PlatformUserId) 混用，也不得为两者建立隐式
//! 转换。

