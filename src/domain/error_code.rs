//! 稳定领域错误码。
//!
//! 错误码是机器可读的契约：格式为 `<域>.<小写下划线标识>`，随版本发布后
//! 不得改变拼写与含义；新增错误变体必须新增错误码。玩家可见文案由命令层
//! 生成（设计方案书 23.3），错误码供日志、审计和未来网页 API 使用。
//!
//! 契约通过 [`StableErrorCode`] 表达，实现位于各错误的所有者模块：战斗
//! 错误在 `combat`，数据库错误在 `database`。本模块不反向依赖任何实现
//! 模块，保持领域层依赖方向（设计方案书 6.1）。

/// 提供稳定错误码的领域错误。
pub trait StableErrorCode {
    /// 稳定错误码，例如 `combat.missing_teams`。
    fn error_code(&self) -> &'static str;
}

